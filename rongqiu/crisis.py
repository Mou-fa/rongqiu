def _normalize(text: str) -> str:
    s = str(text or "")
    for b in _BENIGN:
        s = s.replace(b, "")
    for n in _NEGATED:
        s = s.replace(n, "")
    return s


def matched_tags(text: str) -> list[str]:
    """返回命中的轻生标签；只用于内部测试/审计，不展示给用户。"""
    s = _normalize(text)
    return [tag for tag, words in CRISIS_TAGS.items()
            if any(p in s for p in words)]


def detect(text: str) -> bool:
    """这条输入是否表达了自伤 / 自杀 / 绝望。"""
    return bool(matched_tags(text))


def detect_any(texts: list[str]) -> bool:
    """任何一段用户输入命中都算；用于 question + stated 等多段文本。"""
    return any(detect(t) for t in texts if t)


